"""Write requirements.txt: requirements.in resolved by pip, every file hashed from PyPI's JSON API.

    pyrun python scripts/lock_requirements.py

pip-compile --generate-hashes downloads every platform's wheel to hash it, which takes hours for
sherpa-onnx on this connection; PyPI already publishes each file's sha256.
"""

import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


def resolve() -> list[tuple[str, str]]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "-q", "--dry-run", "--ignore-installed",
                        "--report", str(report), "-r", str(REPO / "requirements.in")], check=True)
        installs = json.loads(report.read_text())["install"]
    return sorted((i["metadata"]["name"].lower().replace("_", "-"), i["metadata"]["version"]) for i in installs)


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=60) as response:
        files = json.load(response)["urls"]
    return sorted(f["digests"]["sha256"] for f in files)


def main() -> int:
    lines = ["# Generated by scripts/lock_requirements.py from requirements.in; do not edit.", ""]
    for name, version in resolve():
        lines.append(f"{name}=={version} \\")
        digests = hashes(name, version)
        lines += [f"    --hash=sha256:{d}" + (" \\" if n < len(digests) - 1 else "") for n, d in enumerate(digests)]
    (REPO / "requirements.txt").write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
